#[rustfmt::skip]
#[derive(rkyv::Archive, rkyv::Serialize, rkyv::Deserialize, Clone, Debug, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "datom", derive(datom_codec::Datomizable, datom_codec::Composing))]
pub enum Output {
    Modules(std::vec::Vec<Module>),
    ModulesVerbose(std::vec::Vec<ModuleDescription>),
    SkillsResolved(std::vec::Vec<ModuleIdentity>),
    SourcesResolved(std::vec::Vec<ResolvedModule>),
    StartupComposed(StartupComposition),
    RoleComposed(RoleComposition),
    Rejected(String),
}
#[rustfmt::skip]
#[allow(clippy::result_large_err, clippy::ptr_arg, clippy::borrowed_box)]
pub trait Answering {
    fn modules(&self) -> std::result::Result<std::vec::Vec<Module>, Output>;
    fn modules_verbose(
        &self,
    ) -> std::result::Result<std::vec::Vec<ModuleDescription>, Output>;
    fn resolve_skills(
        &self,
        module_identity_vector: &std::vec::Vec<ModuleIdentity>,
    ) -> std::result::Result<std::vec::Vec<ModuleIdentity>, Output>;
    fn resolve_sources(
        &self,
        module_identity_vector: &std::vec::Vec<ModuleIdentity>,
    ) -> std::result::Result<std::vec::Vec<ResolvedModule>, Output>;
    fn compose_startup(
        &self,
        startup_selection: &StartupSelection,
    ) -> std::result::Result<StartupComposition, Output>;
    fn compose_role(
        &self,
        role_selection: &RoleSelection,
    ) -> std::result::Result<RoleComposition, Output>;
}
#[rustfmt::skip]
pub trait Answerable {
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Output;
}
#[rustfmt::skip]
impl Answerable for Input {
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Output {
        match self {
            Input::Modules => {
                nexus.modules().map_or_else(|refusal| refusal, Output::Modules)
            }
            Input::ModulesVerbose => {
                nexus
                    .modules_verbose()
                    .map_or_else(|refusal| refusal, Output::ModulesVerbose)
            }
            Input::ResolveSkills(carried) => {
                nexus
                    .resolve_skills(carried)
                    .map_or_else(|refusal| refusal, Output::SkillsResolved)
            }
            Input::ResolveSources(carried) => {
                nexus
                    .resolve_sources(carried)
                    .map_or_else(|refusal| refusal, Output::SourcesResolved)
            }
            Input::ComposeStartup(carried) => {
                nexus
                    .compose_startup(carried)
                    .map_or_else(|refusal| refusal, Output::StartupComposed)
            }
            Input::ComposeRole(carried) => {
                nexus
                    .compose_role(carried)
                    .map_or_else(|refusal| refusal, Output::RoleComposed)
            }
        }
    }
}
